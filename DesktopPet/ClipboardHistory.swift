import AppKit
import Observation

/// One saved copy.
struct ClipboardEntry: Codable, Identifiable, Equatable {
    enum Kind: Codable, Equatable {
        case text(String)
        /// The image itself is saved as a PNG file next to the history (see `ClipboardHistory.imageURL`).
        case image(width: Int, height: Int)
        case files([URL])
    }

    var id = UUID()
    var kind: Kind
    var copiedAt = Date()
}

/// Remembers the last few things copied anywhere on the Mac, text, images and files.
///
/// macOS doesn't announce clipboard changes, so this checks `changeCount` twice a second
/// (cheap, and it doesn't read the contents). Reading the contents is what triggers macOS's
/// "allow paste" permission the first time.
@Observable
final class ClipboardHistory {
    /// Newest first.
    private(set) var entries: [ClipboardEntry] = []

    static let limit = 5

    @ObservationIgnored private var lastChangeCount = NSPasteboard.general.changeCount
    @ObservationIgnored private var pollTimer: Timer?
    @ObservationIgnored private var imageCache: [UUID: NSImage] = [:]

    private static let folder: URL = {
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        let folder = base.appendingPathComponent("DesktopPet/Clipboard", isDirectory: true)
        try? FileManager.default.createDirectory(at: folder, withIntermediateDirectories: true)
        return folder
    }()
    private static var indexURL: URL { folder.appendingPathComponent("history.json") }

    /// Types that password managers and similar apps use to say "don't keep this".
    private static let skippedTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    init() {
        load()
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.checkForNewCopy() }
        RunLoop.main.add(timer, forMode: .common)
        pollTimer = timer
    }

    // MARK: - Using entries

    /// Puts an entry back on the clipboard (and moves it to the top), ready to paste.
    func copyToClipboard(_ entry: ClipboardEntry) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch entry.kind {
        case .text(let text):
            pasteboard.setString(text, forType: .string)
        case .image:
            if let image = image(for: entry) { pasteboard.writeObjects([image]) }
        case .files(let urls):
            pasteboard.writeObjects(urls as [NSURL])
        }
        lastChangeCount = pasteboard.changeCount // our own write isn't a new copy
        moveToTop(entry.id)
    }

    func delete(_ id: ClipboardEntry.ID) {
        if let entry = entries.first(where: { $0.id == id }) { removeFiles(for: entry) }
        entries.removeAll { $0.id == id }
        save()
    }

    func clear() {
        entries.forEach(removeFiles)
        entries.removeAll()
        save()
    }

    func image(for entry: ClipboardEntry) -> NSImage? {
        guard case .image = entry.kind else { return nil }
        if let cached = imageCache[entry.id] { return cached }
        let image = NSImage(contentsOf: Self.imageURL(for: entry.id))
        imageCache[entry.id] = image
        return image
    }

    /// Whether macOS is blocking this app from reading the clipboard (the user chose Deny).
    var isAccessDenied: Bool {
        if #available(macOS 26.0, *) {
            return NSPasteboard.general.accessBehavior == .alwaysDeny
        }
        return false
    }

    // MARK: - Watching the clipboard

    private func checkForNewCopy() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.skippedTypes) else { return } // e.g. a copied password

        if let kind = readKind(from: pasteboard, types: types) {
            add(kind)
        }
    }

    private func readKind(from pasteboard: NSPasteboard, types: Set<NSPasteboard.PasteboardType>) -> PendingKind? {
        if types.contains(.fileURL),
           let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return .files(urls)
        }
        // Text wins over images: copying text from many apps also includes a picture of it.
        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            return .text(text)
        }
        if let image = NSImage(pasteboard: pasteboard), let png = Self.pngData(image) {
            return .image(png, width: Int(image.representations.first?.pixelsWide ?? Int(image.size.width)),
                          height: Int(image.representations.first?.pixelsHigh ?? Int(image.size.height)))
        }
        return nil
    }

    private enum PendingKind {
        case text(String)
        case image(Data, width: Int, height: Int)
        case files([URL])
    }

    private func add(_ pending: PendingKind) {
        let entry: ClipboardEntry
        switch pending {
        case .text(let text):
            // Copying the same thing again just moves it back to the top.
            if let existing = entries.first(where: { $0.kind == .text(text) }) {
                moveToTop(existing.id)
                return
            }
            entry = ClipboardEntry(kind: .text(text))
        case .files(let urls):
            if let existing = entries.first(where: { $0.kind == .files(urls) }) {
                moveToTop(existing.id)
                return
            }
            entry = ClipboardEntry(kind: .files(urls))
        case .image(let png, let width, let height):
            entry = ClipboardEntry(kind: .image(width: width, height: height))
            try? png.write(to: Self.imageURL(for: entry.id))
        }

        entries.insert(entry, at: 0)
        while entries.count > Self.limit {
            removeFiles(for: entries.removeLast())
        }
        save()
    }

    private func moveToTop(_ id: ClipboardEntry.ID) {
        guard let index = entries.firstIndex(where: { $0.id == id }), index > 0 else { return }
        var entry = entries.remove(at: index)
        entry.copiedAt = Date()
        entries.insert(entry, at: 0)
        save()
    }

    // MARK: - Saving

    static func imageURL(for id: UUID) -> URL {
        folder.appendingPathComponent("\(id.uuidString).png")
    }

    private func removeFiles(for entry: ClipboardEntry) {
        if case .image = entry.kind {
            try? FileManager.default.removeItem(at: Self.imageURL(for: entry.id))
            imageCache[entry.id] = nil
        }
    }

    private func load() {
        guard let data = try? Data(contentsOf: Self.indexURL),
              let saved = try? JSONDecoder().decode([ClipboardEntry].self, from: data) else { return }
        entries = saved
    }

    private func save() {
        if let data = try? JSONEncoder().encode(entries) {
            try? data.write(to: Self.indexURL, options: .atomic)
        }
    }

    private static func pngData(_ image: NSImage) -> Data? {
        guard let tiff = image.tiffRepresentation, let bitmap = NSBitmapImageRep(data: tiff) else { return nil }
        return bitmap.representation(using: .png, properties: [:])
    }
}
